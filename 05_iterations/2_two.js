// while loop -

// initialization
// while (condition) {

//     statements

//     termination statement
// }

let index = 1
while (index <= 10) {
    console.log(`Value of index is ${index}`);
    index += 2;
}


// while on Array

let myArray = ["Flash", "Batman", "Superman"]

let arr = 0
while (arr < myArray.length) {
    console.log(`Value is ${myArray[arr]}`);
    arr++;
}



// do-while loop -

// initialization
// do {
    
//     statements

//     termination statement
// } while (condition);



let score = 1

do {
    console.log(`Score is ${score}`);
    score++;
} while (score <= 10);